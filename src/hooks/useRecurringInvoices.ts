import { useQuery, useMutation, useQueryClient } from "@tanstack/react-query";
import { supabase } from "@/integrations/supabase/client";

export interface RecurringInvoice {
  id: string;
  user_id: string;
  source_invoice_id: string;
  customer_id: string;
  frequency: "weekly" | "monthly" | "quarterly" | "annually";
  next_run_date: string;
  is_active: boolean;
  auto_issue: boolean;
  notify_days_before: number | null;
  created_at: string;
  updated_at: string;
  last_generated_at: string | null;
  total_generated: number;
}

export interface PendingRecurringDraft {
  id: string;
  customer_id: string;
  total_amount: number | null;
  invoice_date: string | null;
  source_recurring_id: string;
  customers: { name: string } | null;
  recurring_invoice: { frequency: string } | null;
}

export function useRecurringSchedule(invoiceId: string | undefined) {
  return useQuery({
    queryKey: ["recurringSchedule", invoiceId],
    queryFn: async () => {
      const { data, error } = await supabase
        .from("recurring_invoices")
        .select("*")
        .eq("source_invoice_id", invoiceId!)
        .maybeSingle();
      if (error) throw error;
      return data as RecurringInvoice | null;
    },
    enabled: !!invoiceId,
  });
}

export function useActiveRecurringSchedules(userId: string | undefined) {
  return useQuery({
    queryKey: ["activeRecurringSchedules", userId],
    queryFn: async () => {
      const { data, error } = await supabase
        .from("recurring_invoices")
        .select("*, customers(name)")
        .eq("user_id", userId!)
        .eq("is_active", true)
        .order("next_run_date", { ascending: true });
      if (error) throw error;
      return (data || []) as (RecurringInvoice & { customers: { name: string } | null })[];
    },
    enabled: !!userId,
  });
}

export function useRecurringSourceInvoiceIds(userId: string | undefined) {
  return useQuery({
    queryKey: ["recurringSourceIds", userId],
    queryFn: async () => {
      const { data, error } = await supabase
        .from("recurring_invoices")
        .select("source_invoice_id")
        .eq("user_id", userId!)
        .eq("is_active", true);
      if (error) throw error;
      return new Set((data || []).map((r: any) => r.source_invoice_id));
    },
    enabled: !!userId,
  });
}

/** Unissued draft invoices generated by a recurring schedule — awaiting user review. */
export function usePendingRecurringDrafts(userId: string | undefined) {
  return useQuery({
    queryKey: ["pendingRecurringDrafts", userId],
    queryFn: async () => {
      const { data, error } = await supabase
        .from("invoices")
        .select(`
          id,
          customer_id,
          total_amount,
          invoice_date,
          source_recurring_id,
          customers ( name ),
          recurring_invoice:recurring_invoices!source_recurring_id ( frequency )
        `)
        .eq("user_id", userId!)
        .eq("status", "draft")
        .not("source_recurring_id", "is", null)
        .order("invoice_date", { ascending: true });
      if (error) throw error;
      return (data || []) as PendingRecurringDraft[];
    },
    enabled: !!userId,
  });
}

export function useUpsertRecurringSchedule() {
  const queryClient = useQueryClient();

  return useMutation({
    mutationFn: async (params: {
      invoiceId: string;
      userId: string;
      customerId: string;
      frequency: string;
      nextRunDate: string;
      autoIssue?: boolean;
      notifyDaysBefore?: number | null;
    }) => {
      // Atomic upsert — ON CONFLICT on source_invoice_id guarantees no duplicates
      const { error } = await supabase.from("recurring_invoices").upsert(
        {
          source_invoice_id: params.invoiceId,
          user_id: params.userId,
          customer_id: params.customerId,
          frequency: params.frequency,
          next_run_date: params.nextRunDate,
          is_active: true,
          auto_issue: params.autoIssue ?? false,
          notify_days_before: params.notifyDaysBefore ?? null,
        },
        { onConflict: "source_invoice_id" },
      );
      if (error) throw error;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ["recurringSchedule"] });
      queryClient.invalidateQueries({ queryKey: ["activeRecurringSchedules"] });
      queryClient.invalidateQueries({ queryKey: ["recurringSourceIds"] });
    },
  });
}

export function useToggleRecurringSchedule() {
  const queryClient = useQueryClient();

  return useMutation({
    mutationFn: async (params: { scheduleId: string; isActive: boolean }) => {
      const { error } = await supabase
        .from("recurring_invoices")
        .update({ is_active: params.isActive })
        .eq("id", params.scheduleId);
      if (error) throw error;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ["recurringSchedule"] });
      queryClient.invalidateQueries({ queryKey: ["activeRecurringSchedules"] });
      queryClient.invalidateQueries({ queryKey: ["recurringSourceIds"] });
    },
  });
}

export function useDeleteRecurringSchedule() {
  const queryClient = useQueryClient();

  return useMutation({
    mutationFn: async (scheduleId: string) => {
      const { error } = await supabase
        .from("recurring_invoices")
        .delete()
        .eq("id", scheduleId);
      if (error) throw error;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ["recurringSchedule"] });
      queryClient.invalidateQueries({ queryKey: ["activeRecurringSchedules"] });
      queryClient.invalidateQueries({ queryKey: ["recurringSourceIds"] });
    },
  });
}
